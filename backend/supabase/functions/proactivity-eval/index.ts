// Supabase Edge Function: proactivity-eval
// Evaluates candidate proactive triggers against the scoring formula,
// quiet hours, sliding-window fatigue, and citation requirements.

import { defaultProactivityEngine } from '../../../src/proactive/proactivity_engine.js';

Deno.serve(async (req: Request) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, {
      status: 204,
      headers: {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type, Authorization',
      },
    });
  }

  try {
    const trigger = await req.json();
    const result = defaultProactivityEngine.evaluateCandidate(trigger);

    return new Response(JSON.stringify(result), {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*',
      },
    });
  } catch (err: any) {
    return new Response(JSON.stringify({ error: err.message }), {
      status: 400,
      headers: {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*',
      },
    });
  }
});
